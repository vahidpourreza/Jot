// Reproducible Unicode data transform. No npm packages or runtime network access.
// Run: node scripts/generate-emoji-data.mjs [--check]
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const version='18.0';
const source=`https://www.unicode.org/Public/${version}.0/emoji/emoji-test.txt`;
const folder=new URL('../assets/emoji/',import.meta.url);
const sourceFile=new URL('emoji-test.txt',folder);
const check=process.argv.includes('--check');
await mkdir(folder,{recursive:true});
let sourceText;
try{sourceText=await readFile(sourceFile,'utf8');}
catch(error){
  if(check||error.code!=='ENOENT')throw error;
  const response=await fetch(source);if(!response.ok)throw new Error(`Unicode download: ${response.status}`);
  sourceText=await response.text();await writeFile(sourceFile,sourceText);
}
if(!sourceText.includes(`# Version: ${version}\n`))throw new Error('Unexpected Unicode version.');
const groups=[],rows=[],aliases=[];let group=-1,subgroup='';
for(const line of sourceText.split(/\r?\n/)){
  const groupMatch=line.match(/^# group: (.+)$/);
  if(groupMatch){group=groups.push(groupMatch[1])-1;continue;}
  const subgroupMatch=line.match(/^# subgroup: (.+)$/);if(subgroupMatch){subgroup=subgroupMatch[1];continue;}
  const match=line.match(/^([0-9A-F ]+)\s*;\s*(fully-qualified|minimally-qualified|unqualified)\s*#\s*\S+\s+E([0-9.]+)\s+(.+)$/);
  if(!match)continue;
  const value=String.fromCodePoint(...match[1].trim().split(/\s+/).map(hex=>parseInt(hex,16)));
  aliases.push(value);
  if(match[2]==='fully-qualified')rows.push([value,match[4],group,subgroup,match[3]]);
}
if(rows.length<3900||new Set(aliases).size!==aliases.length)throw new Error('Incomplete or duplicate Unicode data.');
const hash=createHash('sha256').update(sourceText).digest('hex');
const data={version,source,sha256:hash,groups,rows,aliases};
const outputs=new Map([
  ['emoji-data.js',`// Generated by scripts/generate-emoji-data.mjs; Unicode License V3 in LICENSE.txt.\n'use strict';\nwindow.JotEmojiData=${JSON.stringify(data)};\n`],
  ['emoji-values.txt',aliases.join('\n')+'\n']
]);
for(const [name,content]of outputs){
  const target=new URL(name,folder);
  if(check){if(await readFile(target,'utf8')!==content)throw new Error(`${name} differs from the pinned source.`);}
  else await writeFile(target,content);
}
console.log(JSON.stringify({version,fullyQualified:rows.length,accepted:aliases.length,sha256:hash,checked:check}));
